"""Generate a docker-compose file and shared cluster config for N nodes.

    python -m sim.gen_compose --nodes 12            # writes sim/docker-compose.yml + sim/compose/cluster.yaml
    docker build -f deploy/Dockerfile -t edgecluster:latest .
    docker compose -f sim/docker-compose.yml up -d

Node *i* is reachable from the host at ``http://localhost:<8000+i>``. The
uplink schedule is compressed (a 20 s window every 30 s) so convergence is
visible in under a minute. Put an exported model in ``./runs/<name>/onnx``
and pass ``--model-dir`` to also serve ``/classify``.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml


def cluster_config(n: int, model_dir: str | None) -> dict[str, Any]:
    """Config shared by every container (node id comes from EDGE_NODE_ID)."""
    cfg: dict[str, Any] = {
        "cluster": {
            "peers": [{"id": f"node{i}", "url": f"http://node{i}:8000"} for i in range(1, n + 1)],
            "uplink": {"period": "30s", "utc_offset": 0, "windows": [{"start": 0, "duration": "20s"}]},
            "sync": {"interval": "2s", "fanout": 2, "timeout": "3s", "suspect_after": "30s"},
        },
        "data_dir": "/data",
        "admin_enabled": True,
    }
    if model_dir:
        cfg["classifier"] = {"model_dir": "/models", "model_file": "model.pruned.int8.onnx"}
    return cfg


def compose(n: int, model_dir: str | None) -> dict[str, Any]:
    """docker-compose document."""
    services: dict[str, Any] = {}
    for i in range(1, n + 1):
        svc: dict[str, Any] = {
            "image": "edgecluster:latest",
            "pull_policy": "never",  # built locally: `make docker-build`
            "environment": {"EDGE_NODE_ID": f"node{i}"},
            "command": ["--config", "/config/cluster.yaml"],
            "volumes": ["./compose:/config:ro", f"node{i}-data:/data"],
            "ports": [f"{8000 + i}:8000"],
            "restart": "unless-stopped",
            "mem_limit": "1g" if model_dir else "256m",
        }
        if model_dir:
            svc["volumes"].append(f"{model_dir}:/models:ro")
        services[f"node{i}"] = svc
    return {
        "name": "edgecluster",
        "services": services,
        "volumes": {f"node{i}-data": {} for i in range(1, n + 1)},
    }


def main() -> None:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nodes", type=int, default=12)
    ap.add_argument("--model-dir", help="host path (relative to sim/) of an exported ONNX dir")
    ap.add_argument("--out", default="sim")
    args = ap.parse_args()
    out = Path(args.out)
    (out / "compose").mkdir(parents=True, exist_ok=True)
    header = f"# Generated by `python -m sim.gen_compose --nodes {args.nodes}`. Do not edit by hand.\n"
    (out / "compose" / "cluster.yaml").write_text(header + yaml.safe_dump(cluster_config(args.nodes, args.model_dir), sort_keys=False))
    (out / "docker-compose.yml").write_text(header + yaml.safe_dump(compose(args.nodes, args.model_dir), sort_keys=False))
    print(f"wrote {out / 'docker-compose.yml'} and {out / 'compose' / 'cluster.yaml'} for {args.nodes} nodes")


if __name__ == "__main__":
    main()
